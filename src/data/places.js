function firstChunk(s) {
  return (s || "").split(/,|;| — /)[0].replace(/\.$/, "").trim();
}

function rowToPlace(iso, row) {
  const [id, name, type, region, lat, lng, people, culture, food, heritage, historic, wildlife] = row;
  const catalog = catalogFor(id);
  const fields = { people, culture, food, heritage, historic, wildlife };
  const items = {};
  for (const key of Object.keys(fields)) {
    items[key] = catalog?.[key] || itemsFromText(fields[key], name);
  }
  return {
    id,
    iso,
    name,
    type,
    region,
    lat,
    lng,
    people,
    culture,
    food,
    heritage,
    historic,
    wildlife,
    items,
    queries: {
      food: `${firstChunk(food)} ${name}`,
      heritage: firstChunk(heritage),
      historic: `${firstChunk(historic)} ${name}`,
      wildlife: `${firstChunk(wildlife)}`,
      people: `${name} festival`,
    },
  };
}

export const PLACES = {
  in: { label: "States, territories & cities", items: INDIA.map((row) => rowToPlace("in", row)) },
};

for (const [iso, pack] of Object.entries(OTHER)) {
  PLACES[iso] = { label: pack.label, items: pack.items.map((row) => rowToPlace(iso, row)) };
}

for (const [iso, rows] of Object.entries(DIVISIONS)) {
  const pack = PLACES[iso] || { label: "Administrative divisions", items: [] };
  const seen = new Set(pack.items.map((p) => p.id));
  for (const row of rows) {
    const place = rowToPlace(iso, row);
    if (seen.has(place.id)) continue;
    seen.add(place.id);
    pack.items.push(place);
  }
  if (pack.items.some((p) => p.type === "state")) pack.label = "Divisions & cities";
  PLACES[iso] = pack;
}

export function placesFor(iso) {
  return PLACES[iso] || { label: "Cities", items: [] };
}

const PLACE_SEARCH = [];
for (const pack of Object.values(PLACES)) {
  for (const p of pack.items) {
    PLACE_SEARCH.push({
      place: p,
      blob: `${p.name}\n${p.region}\n${p.id}`.toLowerCase(),
    });
  }
}

export function findPlaces(query) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const hits = [];
  for (let i = 0; i < PLACE_SEARCH.length && hits.length < 8; i++) {
    if (PLACE_SEARCH[i].blob.includes(q)) hits.push(PLACE_SEARCH[i].place);
  }
  return hits;
}

export function getPlace(iso, placeId) {
  return placesFor(iso).items.find((p) => p.id === placeId) || null;
}
