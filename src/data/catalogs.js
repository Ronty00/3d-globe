export function itemsFromText(text, placeName) {
  if (!text) return [];
  return text
    .split(/,|;| and /)
    .map((s) => s.replace(/\.$/, "").trim())
    .filter((s) => s.length > 3)
    .slice(0, 18)
    .map((name) => ({ name, note: "", query: `${name} ${placeName}` }));
}
